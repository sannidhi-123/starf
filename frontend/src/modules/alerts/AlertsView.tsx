import React, { useState } from "react";
import {
  AlertOctagon,
  AlertTriangle,
  CheckCircle2,
  Filter,
  Flame,
  RefreshCw,
  Search,
  Shield,
  ShieldAlert,
  Trash2,
  X,
} from "lucide-react";
import { clearAlerts, deleteAlert } from "../../shared/api/client";
import type { AlertItem, AlertSummary } from "../../shared/types";

interface AlertsViewProps {
  alerts: AlertItem[];
  alertsSummary: AlertSummary | null;
  loading: boolean;
  onRefresh: () => void;
  severityFilter: string;
  onSeverityFilterChange: (sev: string) => void;
  runIdFilter: string;
  onRunIdFilterChange: (runId: string) => void;
}

export function AlertsView({
  alerts,
  alertsSummary,
  loading,
  onRefresh,
  severityFilter,
  onSeverityFilterChange,
  runIdFilter,
  onRunIdFilterChange,
}: AlertsViewProps) {
  const [searchQuery, setSearchQuery] = useState("");
  const [canIdQuery, setCanIdQuery] = useState("");
  const [ruleQuery, setRuleQuery] = useState("");
  const [deleteConfirmId, setDeleteConfirmId] = useState<number | null>(null);
  const [showPurgeModal, setShowPurgeModal] = useState(false);
  const [deleting, setDeleting] = useState(false);
  const [actionMsg, setActionMsg] = useState<string | null>(null);

  // Client-side text search (matches CAN ID, Rule IDs, or Reason)
  const filteredAlerts = alerts.filter((a) => {
    if (canIdQuery.trim() && !a.can_id_hex.toLowerCase().includes(canIdQuery.toLowerCase()) && !String(a.can_id).includes(canIdQuery)) return false;
    if (ruleQuery.trim() && !a.rule_ids.toLowerCase().includes(ruleQuery.toLowerCase())) return false;
    if (!searchQuery.trim()) return true;
    const q = searchQuery.toLowerCase();
    return (
      a.can_id_hex.toLowerCase().includes(q) ||
      String(a.can_id).includes(q) ||
      a.rule_ids.toLowerCase().includes(q) ||
      a.reason.toLowerCase().includes(q) ||
      a.label.toLowerCase().includes(q) ||
      String(a.id).includes(q)
    );
  });

  const handleDeleteOne = async (id: number) => {
    setDeleting(true);
    setActionMsg(null);
    try {
      await deleteAlert(id);
      setDeleteConfirmId(null);
      setActionMsg(`Alert #${id} deleted.`);
      onRefresh();
    } catch (err) {
      setActionMsg(`Failed to delete alert: ${err instanceof Error ? err.message : "Error"}`);
    } finally {
      setDeleting(false);
    }
  };

  const handlePurgeAll = async () => {
    setDeleting(true);
    setActionMsg(null);
    try {
      const res = await clearAlerts();
      setShowPurgeModal(false);
      setActionMsg(`Purged all ${res.deleted} alert records from database.`);
      onRefresh();
    } catch (err) {
      setActionMsg(`Failed to purge alerts: ${err instanceof Error ? err.message : "Error"}`);
    } finally {
      setDeleting(false);
    }
  };

  return (
    <div className="space-y-8">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 pb-6 border-b border-slate-800">
        <div>
          <h1 className="text-2xl font-bold tracking-tight text-white flex items-center gap-2">
            <ShieldAlert className="text-rose-400" />
            <span>Intrusion Alert Console</span>
          </h1>
          <p className="mt-1 text-sm text-slate-400">
            Real-time security events generated by Stage 1 deterministic rules and Stage 2 neural arbitration
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={() => setShowPurgeModal(true)}
            disabled={alerts.length === 0 || loading}
            className="inline-flex items-center gap-1.5 rounded-lg border border-rose-500/30 bg-rose-500/10 px-3.5 py-2 text-xs font-semibold text-rose-300 hover:bg-rose-500/20 disabled:opacity-40 transition-colors"
          >
            <Trash2 size={14} />
            <span>Purge Alerts</span>
          </button>
          <button
            onClick={onRefresh}
            disabled={loading}
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 bg-slate-850 px-3.5 py-2 text-xs font-semibold text-slate-200 hover:bg-slate-800 hover:text-white disabled:opacity-50 transition-colors"
          >
            <RefreshCw size={14} className={loading ? "animate-spin text-cyan-400" : ""} />
            <span>Refresh</span>
          </button>
        </div>
      </div>

      {actionMsg && (
        <div className="rounded-lg bg-cyan-500/10 border border-cyan-500/30 p-3 text-xs text-cyan-300 flex items-center justify-between">
          <span>{actionMsg}</span>
          <button onClick={() => setActionMsg(null)} className="text-cyan-400 hover:text-white">
            <X size={14} />
          </button>
        </div>
      )}

      {/* Summary Stat Pills */}
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-4">
        <div className="rounded-xl border border-slate-800 bg-slate-900/60 p-4">
          <p className="text-xs font-mono uppercase text-slate-400">Total Alerts</p>
          <p className="text-2xl font-bold text-white mt-1 font-mono">
            {alertsSummary?.total ?? alerts.length}
          </p>
        </div>
        <div className="rounded-xl border border-slate-800 bg-slate-900/60 p-4">
          <p className="text-xs font-mono uppercase text-rose-400 flex items-center gap-1">
            <Flame size={13} /> CRITICAL
          </p>
          <p className="text-2xl font-bold text-rose-400 mt-1 font-mono">
            {alertsSummary?.by_severity?.CRITICAL ?? 0}
          </p>
        </div>
        <div className="rounded-xl border border-slate-800 bg-slate-900/60 p-4">
          <p className="text-xs font-mono uppercase text-orange-400 flex items-center gap-1">
            <AlertOctagon size={13} /> HIGH
          </p>
          <p className="text-2xl font-bold text-orange-400 mt-1 font-mono">
            {alertsSummary?.by_severity?.HIGH ?? 0}
          </p>
        </div>
        <div className="rounded-xl border border-slate-800 bg-slate-900/60 p-4">
          <p className="text-xs font-mono uppercase text-amber-400 flex items-center gap-1">
            <AlertTriangle size={13} /> MEDIUM
          </p>
          <p className="text-2xl font-bold text-amber-400 mt-1 font-mono">
            {alertsSummary?.by_severity?.MEDIUM ?? 0}
          </p>
        </div>
      </div>

      {/* Filter & Search Bar */}
      <div className="rounded-xl border border-slate-800 bg-slate-900/60 p-4 backdrop-blur-sm flex flex-col md:flex-row items-stretch md:items-center justify-between gap-4">
        {/* Severity Selector */}
        <div className="flex flex-wrap items-center gap-2">
              <span className="text-xs font-semibold uppercase tracking-wider text-slate-400 flex items-center gap-1">
            <Filter size={13} /> Severity:
          </span>
          {["ALL", "CRITICAL", "HIGH", "MEDIUM", "LOW"].map((sev) => (
            <button
              key={sev}
              onClick={() => onSeverityFilterChange(sev)}
              className={`rounded-lg px-2.5 py-1 text-xs font-semibold transition-all ${
                severityFilter === sev
                  ? "bg-cyan-500 text-slate-950 font-bold"
                  : "bg-slate-950 text-slate-400 hover:text-white border border-slate-800"
              }`}
            >
              {sev}
            </button>
          ))}
        </div>

        {/* Search input & Run ID filter */}
        <div className="flex flex-col sm:flex-row flex-wrap items-center gap-2">
          <input aria-label="Filter by CAN ID" type="text" value={canIdQuery} onChange={(e) => setCanIdQuery(e.target.value)} placeholder="Filter CAN ID" className="w-full sm:w-28 rounded-lg border border-slate-800 bg-slate-950 px-3 py-1.5 text-xs text-white placeholder-slate-600 focus:border-cyan-500 focus:outline-none font-mono" />
          <input aria-label="Filter by rule ID" type="text" value={ruleQuery} onChange={(e) => setRuleQuery(e.target.value)} placeholder="Filter rule" className="w-full sm:w-28 rounded-lg border border-slate-800 bg-slate-950 px-3 py-1.5 text-xs text-white placeholder-slate-600 focus:border-cyan-500 focus:outline-none font-mono" />
          <div className="relative w-full sm:w-48">
            <input
              type="text"
              value={runIdFilter}
              onChange={(e) => onRunIdFilterChange(e.target.value)}
              placeholder="Filter by Run ID..."
              className="w-full rounded-lg border border-slate-800 bg-slate-950 px-3 py-1.5 text-xs font-mono text-cyan-300 placeholder-slate-600 focus:border-cyan-500 focus:outline-none"
            />
          </div>

          <div className="relative w-full sm:w-60">
            <Search size={14} className="absolute left-3 top-2.5 text-slate-500" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search CAN ID, rules..."
              className="w-full rounded-lg border border-slate-800 bg-slate-950 pl-9 pr-3 py-1.5 text-xs text-white placeholder-slate-600 focus:border-cyan-500 focus:outline-none font-mono"
            />
          </div>
        </div>
      </div>

      {/* Alerts Table */}
      <div className="rounded-xl border border-slate-800 bg-slate-900/60 p-6 backdrop-blur-sm">
        {loading ? (
          <div className="py-20 text-center text-slate-400">
            <div className="inline-block h-6 w-6 animate-spin rounded-full border-2 border-cyan-400 border-t-transparent mb-2" />
            <p className="text-sm">Fetching intrusion records from SQLite...</p>
          </div>
        ) : filteredAlerts.length === 0 ? (
          <div className="py-16 text-center text-slate-500">
            <Shield size={40} className="mx-auto mb-3 opacity-40 text-slate-400" />
            <h3 className="text-sm font-semibold text-slate-300">No Alerts Found</h3>
            <p className="text-xs text-slate-500 mt-1 max-w-sm mx-auto">
              No alert records match the selected severity filter or search parameters.
            </p>
          </div>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs font-sans">
              <thead className="bg-slate-950 text-slate-400 font-mono uppercase tracking-wider border-b border-slate-800">
                <tr>
                  <th className="py-3 px-3">ID</th>
                  <th className="py-3 px-3">CAN ID</th>
                  <th className="py-3 px-3">Timestamp (s)</th>
                  <th className="py-3 px-3">Severity</th>
                  <th className="py-3 px-3">Classification</th>
                  <th className="py-3 px-3">Confidence</th>
                  <th className="py-3 px-3">Arbitration Stage</th>
                  <th className="py-3 px-3">Rules</th>
                  <th className="py-3 px-3">Reason</th>
                  <th className="py-3 px-3 text-right">Action</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-800/60">
                {filteredAlerts.map((a) => (
                  <tr key={a.id} className="hover:bg-slate-800/40 transition-colors">
                    <td className="py-3 px-3 font-mono text-slate-500">#{a.id}</td>
                    <td className="py-3 px-3 font-mono font-bold text-cyan-300">{a.can_id_hex}</td>
                    <td className="py-3 px-3 font-mono text-slate-400">{a.timestamp.toFixed(6)}</td>
                    <td className="py-3 px-3">
                      <span
                        className={`inline-block px-2 py-0.5 rounded text-[10px] font-bold ${
                          a.severity_level === "CRITICAL"
                            ? "bg-rose-500/20 text-rose-400 border border-rose-500/30"
                            : a.severity_level === "HIGH"
                            ? "bg-orange-500/20 text-orange-400 border border-orange-500/30"
                            : a.severity_level === "MEDIUM"
                            ? "bg-amber-500/20 text-amber-400 border border-amber-500/30"
                            : "bg-slate-800 text-slate-300"
                        }`}
                      >
                        {a.severity_level} ({a.severity_score})
                      </span>
                    </td>
                    <td className="py-3 px-3 font-semibold uppercase text-slate-200">{a.label}</td>
                    <td className="py-3 px-3 font-mono text-slate-300">
                      {(a.confidence * 100).toFixed(1)}%
                    </td>
                    <td className="py-3 px-3 font-mono text-xs text-slate-400">
                      <span className="bg-slate-950 px-2 py-0.5 rounded border border-slate-800">
                        {a.stage}
                      </span>
                    </td>
                    <td className="py-3 px-3 font-mono text-cyan-400 font-semibold">
                      {a.rule_ids || "—"}
                    </td>
                    <td className="py-3 px-3 text-slate-300 max-w-sm truncate" title={a.reason}>
                      {a.reason}
                      {typeof a.details?.stage2_prediction === "string" && <div className="text-[10px] text-amber-300">Stage 2 ({String(a.details.stage2_mode ?? "unknown")}): {a.details.stage2_prediction}{typeof a.details.stage2_confidence === "number" ? ` · ${(a.details.stage2_confidence * 100).toFixed(1)}%` : ""}</div>}
                      {Boolean(a.details?.shap_values) && typeof a.details?.shap_values === "object" && <div className="text-[10px] text-cyan-300">SHAP: {Object.entries(a.details.shap_values as Record<string, number>).sort((x, y) => Math.abs(y[1]) - Math.abs(x[1])).slice(0, 3).map(([name, value]) => `${name} ${value.toFixed(3)}`).join(" · ")}</div>}
                    </td>
                    <td className="py-3 px-3 text-right">
                      {deleteConfirmId === a.id ? (
                        <div className="inline-flex items-center gap-1">
                          <button
                            onClick={() => handleDeleteOne(a.id)}
                            disabled={deleting}
                            className="rounded bg-rose-500 px-2 py-0.5 text-[10px] font-bold text-white hover:bg-rose-600"
                          >
                            Confirm
                          </button>
                          <button
                            onClick={() => setDeleteConfirmId(null)}
                            className="rounded bg-slate-800 px-2 py-0.5 text-[10px] text-slate-400 hover:text-white"
                          >
                            Cancel
                          </button>
                        </div>
                      ) : (
                        <button
                          onClick={() => setDeleteConfirmId(a.id)}
                          title="Delete this alert"
                          className="rounded p-1 text-slate-500 hover:bg-rose-500/20 hover:text-rose-400 transition-colors"
                        >
                          <Trash2 size={13} />
                        </button>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>

      {/* Purge All Modal Confirmation */}
      {showPurgeModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-950/80 p-4 backdrop-blur-sm">
          <div className="w-full max-w-md rounded-2xl border border-rose-500/30 bg-slate-900 p-6 shadow-2xl">
            <div className="flex items-center gap-3 text-rose-400 mb-3">
              <AlertTriangle size={24} />
              <h3 className="text-base font-bold text-white">Confirm Purge All Alerts</h3>
            </div>
            <p className="text-xs text-slate-300 leading-relaxed">
              This will permanently delete all alert rows from the SQLite database. This action
              cannot be undone.
            </p>
            <div className="mt-6 flex items-center justify-end gap-3">
              <button
                onClick={() => setShowPurgeModal(false)}
                className="rounded-lg px-4 py-2 text-xs font-semibold text-slate-400 hover:text-white"
              >
                Cancel
              </button>
              <button
                onClick={handlePurgeAll}
                disabled={deleting}
                className="rounded-lg bg-rose-500 px-4 py-2 text-xs font-bold text-white hover:bg-rose-600 disabled:opacity-50"
              >
                {deleting ? "Purging..." : "Yes, Purge Everything"}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
