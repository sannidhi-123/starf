class AlertCreate(BaseModel):
    """Input payload to record an alert generated by the detection pipeline."""

    can_id: Optional[str] = Field(
        default=None,
        description="CAN arbitration ID (hex string e.g. '0x000' or integer string)",
    )
    timestamp: Optional[float] = Field(
        default=None,
        ge=0.0,
        description="CAN frame epoch or relative timestamp in seconds",
    )
    message: Optional[str] = Field(
        default=None,
        description="Short alert summary or title",
    )
    description: Optional[str] = Field(
        default=None,
        description="Detailed description of detected anomaly",
    )
    severity: AlertSeverity = Field(
        default=AlertSeverity.MEDIUM,
        description="Alert severity rating (low, medium, high, critical)",
    )
    attack_category: AttackCategory = Field(
        default=AttackCategory.UNKNOWN,
        description="Classified attack vector (dos_flooding, fuzzy_attack, spoofing, etc.)",
    )
    confidence: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Model confidence score or rule certainty (0.0 to 1.0)",
    )
    source: Optional[str] = Field(
        default=None,
        description="Origin source (e.g. 'rule_engine', 'stage2_nn', 'car-hacking')",
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Arbitrary context metadata",
    )
    evidence: Dict[str, Any] = Field(
        default_factory=dict,
        description="Frame data, payload bytes, or anomaly metrics supporting alert",
    )

    @model_validator(mode="after")
    def sync_message_and_description(self) -> "AlertCreate":
        if not self.message and not self.description:
            self.message = f"Detected {self.attack_category.value} anomaly"
            self.description = self.message
        elif self.message and not self.description:
            self.description = self.message
        elif self.description and not self.message:
            self.message = self.description[:80]
        return self

    @field_validator("can_id", mode="before")
    @classmethod
    def normalize_can_id(cls, v: Any) -> Optional[str]:
        if v is None:
            return None
        if isinstance(v, int):
            return f"0x{v:03X}" if v <= 0x7FF else f"0x{v:08X}"
        if isinstance(v, str):
            v_clean = v.strip()
            if v_clean.isdigit():
                iv = int(v_clean)
                return f"0x{iv:03X}" if iv <= 0x7FF else f"0x{iv:08X}"
            return (
                v_clean.upper() if v_clean.startswith("0x") else f"0x{v_clean.upper()}"
            )
        return str(v)


class AlertRecord(BaseModel):
    """Full domain model and response representation of a stored security alert."""

    id: str = Field(description="Unique UUIDv4 alert identifier")
    can_id: Optional[str] = Field(
        default=None, description="Affected CAN arbitration ID"
    )
    timestamp: float = Field(description="Frame or event timestamp")
    message: str = Field(description="Short alert summary")
    description: str = Field(description="Detailed incident narrative")
    severity: AlertSeverity = Field(description="Severity rating")
    status: AlertStatus = Field(
        default=AlertStatus.ACTIVE, description="Lifecycle status"
    )
    attack_category: AttackCategory = Field(
        default=AttackCategory.UNKNOWN, description="Attack classification"
    )
    confidence: Optional[float] = Field(default=None, description="Confidence score")
    source: Optional[str] = Field(default=None, description="Originating component")
    metadata: Dict[str, Any] = Field(
        default_factory=dict, description="Additional context"
    )
    evidence: Dict[str, Any] = Field(
        default_factory=dict, description="Supporting telemetry"
    )
    created_at: datetime = Field(description="System alert creation timestamp")
    acknowledged_at: Optional[datetime] = Field(
        default=None, description="Timestamp when operator acknowledged"
    )
    resolved_at: Optional[datetime] = Field(
        default=None, description="Timestamp when incident was resolved"
    )


class AlertStats(BaseModel):
    """Summary metrics of alerts across status and severity."""

    total: int = 0
    active: int = 0
    acknowledged: int = 0
    resolved: int = 0
    by_severity: Dict[str, int] = Field(default_factory=dict)
    by_attack: Dict[str, int] = Field(default_factory=dict)


# ============================================================================
# Notification Adapter (Requirement 6.E)
# ============================================================================


class NotificationDispatcher:
    """Safe local notification adapter for development and incident logging."""

    def dispatch(self, alert: AlertRecord) -> None:
        level = logging.INFO
        if alert.severity == AlertSeverity.CRITICAL:
            level = logging.ERROR
        elif alert.severity == AlertSeverity.HIGH:
            level = logging.WARNING

        logger.log(
            level,
            "NOTIFICATION DISPATCH [%s] [%s] ID=%s CAN=%s: %s (confidence=%s)",
            alert.severity.value.upper(),
            alert.attack_category.value,
            alert.id,
            alert.can_id or "N/A",
            alert.message,
            alert.confidence if alert.confidence is not None else "N/A",
        )


