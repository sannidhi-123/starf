class AlertSeverity(str, Enum):
    """Severity ratings for security alerts matching Stage 1 & 2 detection."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class AlertStatus(str, Enum):
    """Lifecycle state of an alert."""

    ACTIVE = "active"
    ACKNOWLEDGED = "acknowledged"
    RESOLVED = "resolved"


class AttackCategory(str, Enum):
    """Categorization of automotive CAN anomalies from docs/ARCHITECTURE.md."""

    DOS_FLOODING = "dos_flooding"
    FUZZY_ATTACK = "fuzzy_attack"
    SPOOFING = "spoofing"
    REPLAY_ATTACK = "replay_attack"
    MALFUNCTION = "malfunction"
    UNKNOWN = "unknown"


# ============================================================================
# Domain Exceptions
# ============================================================================


class AlertNotFoundError(Exception):
    """Raised when an alert ID cannot be found."""


class InvalidAlertTransitionError(Exception):
    """Raised when an illegal alert status transition is attempted."""


